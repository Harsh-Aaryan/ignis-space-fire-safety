import { test, expect } from "@playwright/test";
const OUT = process.env.SHOT_DIR!;
const HAB = process.env.HAB ?? "moon";
test.skip(!OUT, "Optional visual capture: set SHOT_DIR and HAB to save scenario screenshots.");
const names: Record<string,string> = { moon: "Moon, 0.165 g", mars: "Mars, 0.38 g", gateway: "Gateway-inspired lunar orbit habitat, about 0 g, conceptual digital twin" };
test("fire sim shot", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("console", (m) => { if (m.type() === "error") errors.push("console: " + m.text().slice(0, 300)); });
  await page.goto("/firetwin", { waitUntil: "domcontentloaded" });
  await expect(page.locator("canvas")).toBeVisible();
  await page.waitForTimeout(3000);
  if (HAB !== "moon") { await page.getByRole("radio", { name: names[HAB], exact: true }).click(); await page.waitForTimeout(4000); }
  await page.getByRole("tab", { name: "Fire scenario" }).click();
  await page.waitForTimeout(2500);
  const origin = page.getByLabel("Fire origin");
  const options = await origin.locator("option").allTextContents();
  console.log("options", options.join(" | "));
  const pick = process.env.PICK ?? "Research workbench";
  await origin.selectOption({ label: options.find((o) => o.includes(pick)) ?? options[1] });
  await page.waitForTimeout(3500);
  await page.screenshot({ path: `${OUT}/${HAB}-0-ready.png` });
  await page.getByRole("button", { name: "60×" }).click();
  await page.getByRole("button", { name: "Start fire scenario" }).click();
  await page.waitForTimeout(6000);
  await page.screenshot({ path: `${OUT}/${HAB}-1-burning.png` });
  console.log("status", await page.getByTestId("fire-status").textContent());
  await page.getByRole("button", { name: "1×", exact: true }).click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${OUT}/${HAB}-2-later.png` });
  console.log("status", await page.getByTestId("fire-status").textContent());
  console.log("errors", JSON.stringify(errors));
  expect(errors).toEqual([]);
});
